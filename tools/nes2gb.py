ENEMY_GROUPS = {0x37: ("GOOMBA", 2, 11), 0x38: ("GOOMBA", 3, 11), 0x39: ("GOOMBA", 2, 7), 0x3A: ("GOOMBA", 3, 7),
                0x3B: ("KOOPA", 2, 11), 0x3C: ("KOOPA", 3, 11), 0x3D: ("KOOPA", 2, 7), 0x3E: ("KOOPA", 3, 7)}


def read_enemy_list(prg, address):
    """[(x pixels, y pixels of the 16x16 body's top, type name)] for normal mode"""
    i = address - 0x8000
    page = 0
    enemies = []
    while prg[i] != 0xFF:
        column, row = prg[i] >> 4, prg[i] & 0x0F
        if row == 0x0E:           # pipe warp
            if prg[i + 1] & 0x80:
                page += 1
            i += 3
            continue
        flags = prg[i + 1]
        i += 2
        if row == 0x0F:           # set page
            page = flags & 0x3F
            continue
        if flags & 0x80:
            page += 1
        if flags & 0x40:          # hard mode (second quest) only
            continue
        x = (page * 16 + column) * 16
        enemy = flags & 0x3F
        if enemy in ENEMY_GROUPS:
            kind, count, group_row = ENEMY_GROUPS[enemy]
            for k in range(count):
                enemies.append((x + k * 24, (group_row + 1) * 16, kind))
        elif enemy in ENEMY_IDS:
            enemies.append((x, (row + 1) * 16, ENEMY_IDS[enemy]))
        else:
            sys.exit("enemy id %02X at x=%d isn't handled yet" % (enemy, x))
    return enemies


# ---- Level (area) data. SMB keeps each area as a 2-byte header and a list of
# 2-byte objects: [column << 4 | row], [page flag (bit 7), kind (bits 6-4),
# length (bits 3-0)]; $FD ends it. Rows 0-11 hold blocks, rows 12-15 special
# objects. The terrain (floor and ceiling pattern) is drawn first, objects over it.
# The decoder handles the objects the areas we use need; anything else stops it.
AREA_DATA_H_OFFSETS, AREA_DATA_LOW, AREA_DATA_HIGH = 0x9D28, 0x9D2C, 0x9D4E
ENEMY_ADDR_H_OFFSETS, ENEMY_DATA_LOW, ENEMY_DATA_HIGH = 0x9CE0, 0x9CE4, 0x9D06
AREA_1_1 = 0x25
# per area type: water, ground, underground, castle
TERRAIN_METATILES = [0x69, 0x54, 0x52, 0x62]
BRICK_METATILES = [0x22, 0x51, 0x52, 0x52]
SOLID_METATILES = [0x69, 0x61, 0x61, 0x62]
COIN_METATILES = [0xC3, 0xC2, 0xC2, 0xC2]
UNDERGROUND_FLOOR = 0x54   # underground terrain turns to ground from row 11 down
# TerrainRenderBits: rows 0-7 in the first byte, rows 8-12 in the second (bit 0 = top)
TERRAIN_BITS = [(0x00, 0x00), (0x00, 0x18), (0x01, 0x18), (0x07, 0x18), (0x0F, 0x18), (0xFF, 0x18),
                (0x01, 0x1F), (0x07, 0x1F), (0x0F, 0x1F), (0x81, 0x1F), (0x01, 0x00), (0x8F, 0x1F),
                (0xF1, 0x1F), (0xF9, 0x18), (0xF1, 0x18), (0xFF, 0x1F)]
# Small objects (kind 0 in rows 0-11) by length: ? blocks, hidden blocks, bricks with items, used block
SMALL_OBJECTS = {0: 0xC1, 1: 0xC0, 2: 0x5F, 3: 0x60, 4: 0x55, 5: 0x56, 6: 0x57, 7: 0x58, 8: 0x59, 0xA: 0xC4}
PLAYER_START_Y = [0x00, 0x20, 0xB0, 0x50, 0x00, 0x00, 0xB0, 0xB0]  # by the header's start position
PLAYER_START_X = 0x28
AREA_ROWS = 13        # SMB's rows 0-12 are our map rows 2-14 (rows 0-1 are under its status bar)
MAP_ROW_OFFSET = 2


def area_type(ptr):
    return (ptr >> 5) & 3


def area_address(prg, ptr, h_offsets, low, high):
    k = prg[h_offsets - 0x8000 + area_type(ptr)] + (ptr & 0x1F)
    return prg[low - 0x8000 + k] | (prg[high - 0x8000 + k] << 8)


def read_warps(prg, ptr):
    """The pipe warps in an area's enemy list: (page it applies from, destination area, world, page there)"""
    i = area_address(prg, ptr, ENEMY_ADDR_H_OFFSETS, ENEMY_DATA_LOW, ENEMY_DATA_HIGH) - 0x8000
    page, warps = 0, []
    while prg[i] != 0xFF:
        row = prg[i] & 0x0F
        if row == 0x0E:
            if prg[i + 1] & 0x80:
                page += 1
            warps.append((page, prg[i + 1] & 0x7F, prg[i + 2] >> 5, prg[i + 2] & 0x1F))
            i += 3
            continue
        if row == 0x0F:
            page = prg[i + 1] & 0x3F
        elif prg[i + 1] & 0x80:
            page += 1
        i += 2
    return warps


BACK_SCENERY_DATA = 0x92FA         # BackSceneryData: 48 columns (3 pages, repeating) per scenery type
BACK_SCENERY_METATILES = 0x938A    # BackSceneryMetatiles: 3 metatiles (top down) per scenery piece
# CastleMetatiles: 5 wide, 11 tall; a castle object draws its top rows down to the floor.
# SMB's second row is $48 $47 $46, which puts the tower's windows at its outer
# edges; here the two are swapped to set them in from the edges, matching the
# hand-made 1-1 castle.
CASTLE_METATILES = [
    [0x00, 0x45, 0x45, 0x45, 0x00], [0x00, 0x46, 0x47, 0x48, 0x00], [0x45, 0x49, 0x49, 0x49, 0x45],
    [0x47, 0x47, 0x4A, 0x47, 0x47], [0x47, 0x47, 0x4B, 0x47, 0x47], [0x49, 0x49, 0x49, 0x49, 0x49],
    [0x47, 0x4A, 0x47, 0x4A, 0x47], [0x47, 0x4B, 0x47, 0x4B, 0x47], [0x47, 0x47, 0x47, 0x47, 0x47],
    [0x4A, 0x47, 0x4A, 0x47, 0x4A], [0x4B, 0x47, 0x4B, 0x47, 0x4B],
]
STAIR_HEIGHTS = [1, 2, 3, 4, 5, 6, 7, 8, 8]   # StaircaseObject: column by column, sitting on the floor
FLOOR_ROW = 10                                # the lowest row objects stand on (the floor is rows 11-12)


class Area:
    """A decoded SMB area: grid[column][row] of SMB metatile numbers, plus the things
    the game needs to know about (pipes and so on)"""
    def __init__(self, header, grid):
        self.header, self.grid = header, grid
        self.pipes = []          # (column, top row, can be entered)
        self.exit_pipe = None    # (column, row of its mouth's top half) of a sideways pipe out
        self.intro_pipe = None   # the same for an intro area's pipe


def decode_area(prg, ptr, width, strict=True):
    """Area for the SMB area `ptr`'s first `width` columns"""
    kind_of_area = area_type(ptr)
    i = area_address(prg, ptr, AREA_DATA_H_OFFSETS, AREA_DATA_LOW, AREA_DATA_HIGH) - 0x8000
    header = (prg[i], prg[i + 1])
    i += 2
    objects, page = [], 0
    while prg[i] != 0xFD:
        b1, b2 = prg[i], prg[i + 1]
        i += 2
        if b2 & 0x80:
            page += 1
        if b1 & 0x0F == 0x0D and not (b2 & 0x40):   # page control: jump to a page
            page = b2 & 0x1F
            continue
        objects.append((page * 16 + (b1 >> 4), b1, b2))
    grid = [[0] * AREA_ROWS for _ in range(width)]
    area = Area(header, grid)
    if header[0] & 0x07 and strict:
        sys.exit("area %02X: foreground scenery %d isn't handled yet" % (ptr, header[0] & 7))

    def put(c, r, m):
        if 0 <= c < width and 0 <= r < AREA_ROWS:
            grid[c][r] = m

    # background scenery (clouds, hills, bushes...), repeating every 3 pages
    scenery = (header[1] >> 4) & 3
    if scenery:
        for c in range(width):
            v = prg[BACK_SCENERY_DATA - 0x8000 + (scenery - 1) * 48 + c % 48]
            if v:
                piece = BACK_SCENERY_METATILES - 0x8000 + ((v & 0x0F) - 1) * 3
                for k in range(3):
                    if prg[piece + k]:
                        put(c, (v >> 4) + k, prg[piece + k])

    # terrain, column by column. A row 14 object changes it from the column after
    # its own: SMB draws each column's terrain before it reads that column's objects.
    terrain = header[1] & 0x0F
    changes = {c + 1: b2 & 0x0F for c, b1, b2 in objects if b1 & 0x0F == 0x0E and not (b2 & 0x40)}
    for c in range(width):
        terrain = changes.get(c, terrain)
        bits = TERRAIN_BITS[terrain][0] | (TERRAIN_BITS[terrain][1] << 8)
        metatile = TERRAIN_METATILES[kind_of_area]
        for r in range(AREA_ROWS):
            if kind_of_area == 2 and r == 11:
                metatile = UNDERGROUND_FLOOR
            if bits & (1 << r):
                grid[c][r] = metatile

    def sideways_pipe(c, length, shaft_top=0):
        """exit/intro pipe: the sideways part at rows length-1..length, joined to a pipe going up"""
        shaft = length - 2
        for k, (top, bottom) in enumerate(((0x1C, 0x1F), (0x1D, 0x20), (0x1E, 0x21), (0x15, 0x15))):
            if k >= 2:
                for r in range(shaft_top, shaft + 1):
                    put(c + k, r, 0x14 if k == 2 else 0x15)
            put(c + k, shaft + 1, top)
            put(c + k, shaft + 2, bottom)
        return (c, shaft + 1)

    for c, b1, b2 in objects:
        if c >= width:
            continue
        row, length, kind = b1 & 0x0F, b2 & 0x0F, (b2 >> 4) & 7
        if row <= 11 and kind == 0 and length in SMALL_OBJECTS:
            m = SMALL_OBJECTS[length]
            if kind_of_area != 1 and 0x55 <= m <= 0x59:
                m += 5   # bricks with items outside ground levels: the plain brick look
            put(c, row, m)
        elif row <= 11 and kind in (2, 3, 4):          # rows of bricks, solid blocks, coins
            m = {2: BRICK_METATILES, 3: SOLID_METATILES, 4: COIN_METATILES}[kind][kind_of_area]
            for k in range(length + 1):
                put(c + k, row, m)
        elif row <= 11 and kind in (5, 6):             # columns of bricks, solid blocks
            m = {5: BRICK_METATILES, 6: SOLID_METATILES}[kind][kind_of_area]
            for k in range(length + 1):
                put(c, row + k, m)
        elif row <= 11 and kind == 7:                  # vertical pipe; bit 3: it can be entered
            enter = bool(b2 & 0x08)
            put(c, row, 0x10 if enter else 0x12)
            put(c + 1, row, 0x11 if enter else 0x13)
            for k in range(1, (b2 & 0x07) + 1):
                put(c, row + k, 0x14)
                put(c + 1, row + k, 0x15)
            area.pipes.append((c, row, enter))
        elif row == 0x0C and kind == 0:                # a pit: rows 8 down to the bottom, cleared
            for k in range(length + 1):
                for r in range(8, AREA_ROWS):
                    put(c + k, r, 0)
        elif row == 0x0C and kind in (6, 7):           # a row of ? blocks (with coins), high or low
            for k in range(length + 1):
                put(c + k, 3 if kind == 6 else 7, 0xC0)
        elif row == 0x0F and kind == 2:                # castle: its top rows, down to the floor
            for r in range(length, FLOOR_ROW + 1):
                for k in range(5):
                    if CASTLE_METATILES[r - length][k]:
                        put(c + k, r, CASTLE_METATILES[r - length][k])
        elif row == 0x0F and kind == 3:                # staircase going up to the right
            for k in range(length + 1):
                for r in range(FLOOR_ROW + 1 - STAIR_HEIGHTS[k], FLOOR_ROW + 1):
                    put(c + k, r, SOLID_METATILES[kind_of_area])
        elif row == 0x0F and kind == 4:                # exit pipe: sideways, joined to a pipe going up
            area.exit_pipe = sideways_pipe(c, length)
        elif row == 0x0D and b2 & 0x40 and (b2 & 0x3F) == 1:   # flagpole: ball, pole, block at its foot
            put(c, 0, 0x24)
            for r in range(1, FLOOR_ROW):
                put(c, r, 0x25)
            put(c, FLOOR_ROW, SOLID_METATILES[kind_of_area])
        elif row == 0x0D and b2 & 0x40 and (b2 & 0x3F) == 0:   # intro pipe: the same, a short pipe above
            area.intro_pipe = sideways_pipe(c, 10, shaft_top=7)
            put(c + 2, 7, 0x10)
            put(c + 3, 7, 0x11)
        elif row in (0x0D, 0x0E):
            pass                                       # scroll locks and such; terrain changes (done above)
        elif strict:
            sys.exit("area %02X: object %02X %02X at column %d isn't handled yet" % (ptr, b1, b2, c))
    return area


def metatile_to_scenery(m):
    """SMB metatile number -> SCENERY_* number (SceneryTiles lists the groups in order)"""
    return sum(len(names) for names in METATILE_NAMES[:m >> 6]) + (m & 0x3F)


# ---- Music. SMB's music engine plays "headers": each points at data for its two
# squares, triangle and noise. Square 2 leads: [length byte (bit 7 set)] note,
# 0 ends the part. Square 1 and noise pack length and note in one byte, the
# triangle works like square 2. Notes index FreqRegLookupTbl; lengths index
# MusicLengthLookupTbl from the header's offset (+8 for the faster "hurry" tempo).
# The songs are simulated frame by frame and written out as per-channel
# (frames, note) lists for the Game Boy: SMB's squares -> pulse 1 and 2, triangle
# -> wave, noise -> noise.
SOUND_BANK = 4
MUSIC_HEADERS = 0xF90D       # MusicHeaderData (song offsets first, then headers)
FREQ_TABLE = 0xFF00          # FreqRegLookupTbl
LENGTH_TABLE = 0xFF66        # MusicLengthLookupTbl
NES_CPU_HZ = 1789773
HURRY_LENGTHS = 8
# Song numbers in MusicHeaderData's list
EVENT_DEATH, EVENT_GAME_OVER, EVENT_END_OF_LEVEL, EVENT_HURRY = 0, 1, 5, 6
AREA_UNDERGROUND, AREA_STAR, AREA_PIPE_INTRO = 10, 12, 13
GROUND_LAYOUT, GROUND_LAYOUT_END, GROUND_LOOP = 16, 49, 17   # the ground theme's parts, and where it loops back to
TRIANGLE_SHORT = 8           # frames a triangle note sounds for SMB's linear counter $1F
TRIANGLE_LONG_FROM = 0x12    # event music holds notes this long or longer ($FF)
# Game Boy pulse envelope per song (NRx2: start volume, fade speed): SMB's area
# music is plucky, its event music (fanfares) held
VOICE_AREA, VOICE_UNDERGROUND, VOICE_EVENT = 0xB2, 0xB1, 0xA5


def music_part(prg, offset, fast, event):
    """{channel: [(frames, note)]} for one part; note 0 is a rest (noise: drum kind 1-3)"""
    rd = lambda a: prg[a - 0x8000]
    h = [rd(MUSIC_HEADERS + offset + k) for k in range(6)]
    lenofs, data, tri, sq1, noise = h[0] + fast, h[1] | (h[2] << 8), h[3], h[4], h[5] if not event else 0
    length = lambda i: rd(LENGTH_TABLE + (i & 7) + lenofs)
    alt = lambda v: ((v & 1) << 2) | ((v >> 7) << 1) | ((v >> 6) & 1)
    note = lambda v: 0 if rd(FREQ_TABLE + v) == 0 and rd(FREQ_TABLE + v + 1) == 0 else v >> 1
    out = {}
    lead, i, n = [], 0, 0
    while rd(data + i):
        v = rd(data + i); i += 1
        if v & 0x80:
            n = length(v); v = rd(data + i); i += 1
        lead.append((n, note(v)))
    out['pulse2'] = lead
    total = sum(n for n, _ in lead)

    def fit(events):   # exactly `total` frames: cut the overhang, pad with a rest
        fitted, t = [], 0
        for n, v in events:
            n = min(n, total - t)
            if n > 0:
                fitted.append((n, v)); t += n
        if t < total:
            fitted.append((total - t, 0))
        return fitted

    if sq1:
        ev, i, t = [], sq1, 0
        while t < total:
            v = rd(data + i); i += 1
            if v == 0:
                continue          # death music's sweep switch
            n = length(alt(v)); ev.append((n, note(v & 0x3E))); t += n
        out['pulse1'] = fit(ev)
    if tri:
        ev, i, t, n = [], tri, 0, 0
        while t < total:
            v = rd(data + i); i += 1
            if v == 0:
                break             # silent for the rest of the part
            if v & 0x80:
                n = length(v); v = rd(data + i); i += 1
                if v == 0:
                    break
            sound = n if (event and n >= TRIANGLE_LONG_FROM) else min(n, TRIANGLE_SHORT)
            ev.append((sound, note(v)))
            if n > sound:
                ev.append((n - sound, 0))
            t += n
        out['wave'] = fit(ev)
    if noise:
        ev, i, t = [], noise, 0
        while t < total:
            v = rd(data + i); i += 1
            if v == 0:
                i = noise; continue   # the beat loops for as long as the part lasts
            k = v & 0x3E
            ev.append((length(alt(v)), 3 if k == 0x30 else 2 if k == 0x20 else 1 if k & 0x10 else 0))
            t += ev[-1][0]
        out['noise'] = fit(ev)
    return out


def write_music(prg):
    """Music (bank 4): SMB's songs for the Game Boy's sound channels"""
    rd = lambda a: prg[a - 0x8000]
    offsets = [rd(MUSIC_HEADERS + i) for i in range(GROUND_LAYOUT_END)]
    ground = list(range(GROUND_LAYOUT, GROUND_LAYOUT_END))
    songs = [  # name, song numbers of its parts, part it loops back to (None: plays once), event music, voice
        ("GROUND", ground, GROUND_LOOP - GROUND_LAYOUT, 0, False, VOICE_AREA),
        ("GROUND_FAST", ground, GROUND_LOOP - GROUND_LAYOUT, HURRY_LENGTHS, False, VOICE_AREA),
        ("UNDERGROUND", [AREA_UNDERGROUND], 0, 0, False, VOICE_UNDERGROUND),
        ("UNDERGROUND_FAST", [AREA_UNDERGROUND], 0, HURRY_LENGTHS, False, VOICE_UNDERGROUND),
        ("STAR", [AREA_STAR], 0, 0, False, VOICE_AREA),
        ("STAR_FAST", [AREA_STAR], 0, HURRY_LENGTHS, False, VOICE_AREA),
        ("HURRY", [EVENT_HURRY], None, 0, True, VOICE_EVENT),
        ("DEATH", [EVENT_DEATH], None, 0, True, VOICE_EVENT),
        ("GAME_OVER", [EVENT_GAME_OVER], None, 0, True, VOICE_EVENT),
        ("LEVEL_CLEAR", [EVENT_END_OF_LEVEL], None, 0, True, VOICE_EVENT),
        ("PIPE_INTRO", [AREA_PIPE_INTRO], None, 0, False, VOICE_AREA),
    ]
    channels = ['pulse1', 'pulse2', 'wave', 'noise']
    parts, part_index, streams = [], {}, {}

    def stream(events):
        data = []
        for n, v in events:
            while n > 255:
                data += [255, v]; n -= 255
            data += [n, v]
        key = tuple(data + [0])
        if key not in streams:
            streams[key] = "musicStream%d" % len(streams)
        return streams[key]

    song_parts = []
    for name, numbers, loop, fast, event, voice in songs:
        idx = []
        for number in numbers:
            key = (offsets[number], fast, event)
            if key not in part_index:
                decoded = music_part(prg, offsets[number], fast, event)
                part_index[key] = len(parts)
                parts.append([stream(decoded[c]) if c in decoded else None for c in channels])
            idx.append(part_index[key])
        song_parts.append(idx)

    # Game Boy frequencies (pulse, and wave with a 32-step wave: the same register
    # value for the same NES timer, as the triangle is also an octave lower)
    freqs = []
    for v in range(0, 0x80, 2):
        hi, lo = rd(FREQ_TABLE + v), rd(FREQ_TABLE + v + 1)
        t = (hi << 8) | lo
        freqs.append(0 if t == 0 else max(0, round(2048 - 131072 * 16 * (t + 1) / NES_CPU_HZ)))

    h = ["/*", " MUSIC.H", "",
         " Super Mario Bros.' music for the Game Boy, read from its own music data. A song",
         " is a list of parts; a part has a stream per channel (pulse 1, pulse 2, wave,",
         " noise; NULL = unused) of (frames, note) byte pairs ending with 0. Notes index",
         " MusicFreqs (0 = rest); the noise channel's are drum kinds 1-3.", "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/",
         "#ifndef __Music_h_INCLUDE", "#define __Music_h_INCLUDE", "",
         "#include <gbdk/platform.h>", "#include <stdint.h>", ""]
    for n, song in enumerate(songs):
        h.append("#define MUSIC_%-18s %d" % (song[0], n))
    h += ["#define MusicSongCount %d" % len(songs), "",
          "#define MUSIC_CHANNELS 4",
          "typedef struct { const uint8_t *channel[MUSIC_CHANNELS]; } MusicPart;",
          "// loop: index of the part it loops back to, MUSIC_NO_LOOP if it plays once",
          "#define MUSIC_NO_LOOP 0xFF",
          "typedef struct { const uint8_t *parts; uint8_t count, loop, voice; } MusicSong;", "",
          "// In ROM bank %d (sound): switch to BANK(Music) before reading them" % SOUND_BANK,
          "BANKREF_EXTERN(Music)",
          "extern const MusicSong MusicSongs[];", "extern const MusicPart MusicParts[];",
          "extern const uint16_t MusicFreqs[];", "", "#endif", ""]
    c = ["/*", " MUSIC.C", "", " See Music.h.", "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/", "",
         "#pragma bank %d" % SOUND_BANK, "", "#include <gbdk/platform.h>", "#include \"Music.h\"", "",
         "BANKREF(Music)", ""]
    for key, name in streams.items():
        c.append("static const uint8_t %s[] = {%s};" % (name, ",".join(str(v) for v in key)))
    c += ["", "const MusicPart MusicParts[] = {"]
    for p in parts:
        c.append("  {{%s}}," % ", ".join(s if s else "NULL" for s in p))
    c += ["};", ""]
    for n, idx in enumerate(song_parts):
        c.append("static const uint8_t songParts%d[] = {%s};" % (n, ",".join(str(i) for i in idx)))
    c += ["", "const MusicSong MusicSongs[] = {"]
    for n, (name, numbers, loop, fast, event, voice) in enumerate(songs):
        c.append("  {songParts%d, %d, %s, 0x%02X}, // %s" % (n, len(song_parts[n]),
                 "MUSIC_NO_LOOP" if loop is None else loop, voice, name))
    c += ["};", "", "const uint16_t MusicFreqs[] = {"]
    c.append("  " + ",".join(str(f) for f in freqs))
    c += ["};", ""]
    folder = os.path.join(ROOT, "assets", "sound")
    os.makedirs(folder, exist_ok=True)
    open(os.path.join(folder, "Music.h"), "w", newline="\n").write("\n".join(h))
    open(os.path.join(folder, "Music.c"), "w", newline="\n").write("\n".join(c))
    size = sum(len(k) for k in streams) + len(parts) * 8 + sum(len(i) for i in song_parts) + len(songs) * 5 + len(freqs) * 2
    print("wrote assets/sound/Music.c/.h (%d songs, %d parts, about %d bytes)" % (len(songs), len(parts), size))


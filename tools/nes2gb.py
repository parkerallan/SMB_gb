def write_scenery(chr_, grays):
    """SceneryTiles: unique tiles plus a table of 4 tile indexes per metatile"""
    prg = chr_.prg
    base = METATILE_TABLE - 0x8000
    pointers = [prg[base + k] | (prg[base + 4 + k] << 8) for k in range(4)]
    unique = {}      # gb bytes -> index
    tiles = []       # (bytes, comment)
    table = []       # (name, [TL, TR, BL, BR] tile indexes)
    for group, names in enumerate(METATILE_NAMES):
        for m, name in enumerate(names):
            o = pointers[group] - 0x8000 + m * 4
            tl, bl, tr, br = prg[o:o + 4]
            idx = []
            for nes in (tl, tr, bl, br):
                data = tuple(to_gb(chr_.tile(BG + nes), grays[group]))
                if data not in unique:
                    unique[data] = len(tiles)
                    tiles.append((list(data), "nes bg %02X (palette %d)" % (nes, group)))
                idx.append(unique[data])
            table.append((name, idx))

    h = ["/*", " SCENERYTILES.H", "",
         " Every 16x16 background block (metatile) Super Mario Bros. can draw: overworld,",
         " underground, castle, water and sky scenery, blocks, pipes, bridges, the axe...",
         " SceneryTiles holds the unique 8x8 tiles; SceneryMetatiles holds 4 tile indexes",
         " per block (TL, TR, BL, BR) and SCENERY_<NAME> is a block's number in it.", "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/",
         "#ifndef __SceneryTiles_h_INCLUDE", "#define __SceneryTiles_h_INCLUDE", "",
         "#include <gbdk/platform.h>", "",
         "#define SceneryTilesCount %d" % len(tiles),
         "#define SceneryMetatileCount %d" % len(table), ""]
    for n, (name, idx) in enumerate(table):
        h.append("#define SCENERY_%-26s %3d" % (name, n))
    h += ["", "// In a switchable ROM bank: switch to BANK(SceneryTiles) before reading either array",
          "BANKREF_EXTERN(SceneryTiles)", "extern const unsigned char SceneryTiles[];",
          "extern const unsigned char SceneryMetatiles[];", "", "#endif", ""]
    c = ["/*", " SCENERYTILES.C", "", " See SceneryTiles.h.", "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/", "",
         "#pragma bank %d" % GRAPHICS_BANK, "", "#include <gbdk/platform.h>", "", "BANKREF(SceneryTiles)", "",
         "const unsigned char SceneryTiles[] =", "{"]
    for data, comment in tiles:
        c.append("  " + ",".join("0x%02X" % v for v in data) + ", // " + comment)
    c += ["};", "", "// 4 SceneryTiles indexes per block: TL, TR, BL, BR",
          "const unsigned char SceneryMetatiles[] =", "{"]
    for name, idx in table:
        c.append("  " + ",".join("%3d" % v for v in idx) + ", // " + name)
    c += ["};", ""]
    out = os.path.join(ROOT, "assets", "tiles", "SceneryTiles")
    open(out + ".h", "w", newline="\n").write("\n".join(h))
    open(out + ".c", "w", newline="\n").write("\n".join(c))
    print("wrote assets/tiles/SceneryTiles.c/.h (%d tiles, %d blocks)" % (len(tiles), len(table)))



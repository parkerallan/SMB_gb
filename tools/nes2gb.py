def area_width(prg, ptr, first_page=0, to_scroll_lock=True):
    """columns from first_page up to the next scroll lock (or the end of the area)"""
    i = area_address(prg, ptr, AREA_DATA_H_OFFSETS, AREA_DATA_LOW, AREA_DATA_HIGH) - 0x8000 + 2
    page, last = 0, 0
    while prg[i] != 0xFD:
        b1, b2 = prg[i], prg[i + 1]
        if b2 & 0x80:
            page += 1
        if b1 & 0x0F == 0x0D and not (b2 & 0x40):
            page = b2 & 0x1F
        column = page * 16 + (b1 >> 4)
        if column >= first_page * 16 + 1:
            if to_scroll_lock and b1 & 0x0F == 0x0D and b2 & 0x40 and (b2 & 0x3F) in SCROLL_LOCKS:
                return column - first_page * 16
            last = max(last, column)
        i += 2
    return last + 1 - first_page * 16


def warp_for(prg, ptr, world, first_page, pages=16):
    """the area's warp for `world` on its pages first_page.. (destination area, page there)"""
    for page, dest, w, dest_page in read_warps(prg, ptr):
        if w == world and first_page <= page < first_page + pages:
            return dest, dest_page
    return None


def pipe_on_page(area, page):
    return [p for p in area.pipes if page * 16 <= p[0] < page * 16 + 16][0]


def start_feet(header):
    """where SMB drops Mario in (x, y of his feet), from the area header's start position"""
    return PLAYER_START_X & ~15, PLAYER_START_Y[(header[0] >> 3) & 7] + SMB_FEET


def write_map(name, grid, first, width, comment, defines):
    """assets/maps/<name>.c/.h: a grid of SCENERY_* blocks, width by 15, row by row"""
    rows = [[0] * width for _ in range(AREA_ROWS + MAP_ROW_OFFSET)]
    for c in range(width):
        for r in range(AREA_ROWS):
            m = grid[first + c][r]
            rows[r + MAP_ROW_OFFSET][c] = metatile_to_scenery(m) if m else 0
    guard = "__%s_h_INCLUDE" % name
    h = ["/*", " %s.H" % name.upper(), ""] + [" " + l for l in comment] + [
         "", " A grid of 16x16 blocks (SCENERY_* numbers), %d wide by %d tall, row by row." % (width, len(rows)),
         " Block rows are the map's (SMB's rows 0-12 are its rows 2-14).", "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/",
         "#ifndef %s" % guard, "#define %s" % guard, "", "#include <gbdk/platform.h>", "",
         "#define %sWidth %d" % (name, width), "#define %sHeight %d" % (name, len(rows)), ""]
    for comment_line, macro, value in defines:
        if comment_line:
            h.append("// " + comment_line)
        h.append("#define %s %d" % (macro, value))
    h += ["", "// In switchable ROM bank 1 (maps): switch to BANK(%s) before reading it" % name,
          "BANKREF_EXTERN(%s)" % name, "extern const unsigned char %s[];" % name, "", "#endif", ""]
    c = ["/*", " %s.C" % name.upper(), "", " See %s.h." % name, "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/", "",
         "#pragma bank 1", "", "#include <gbdk/platform.h>", "", "BANKREF(%s)" % name, "",
         "const unsigned char %s[] =" % name, "{"]
    for row in rows:
        c.append("  " + ",".join("%3d" % v for v in row) + ",")
    c += ["};", ""]
    out = os.path.join(ROOT, "assets", "maps", name)
    open(out + ".h", "w", newline="\n").write("\n".join(h))
    open(out + ".c", "w", newline="\n").write("\n".join(c))
    print("wrote assets/maps/%s.c/.h (%dx%d)" % (name, width, len(rows)))


COIN_ROOMS = 0x42                # the underground area holding the coin rooms, page by page


def write_coin_room(prg, name, level, from_ptr, areas):
    """a coin room that the level area `from_ptr`'s pipe leads to, and where its pipes are;
    `areas` has the decoded level areas by pointer (SMB's pointers can differ in bit 7)"""
    level_prefix = "LEVEL" + level.replace("-", "_")
    room_prefix = level_prefix + "_BONUS"
    page, _, _, room_page = [w for w in read_warps(prg, from_ptr) if w[2] == 0 and w[1] == COIN_ROOMS][0]
    entry = [p for p in areas[from_ptr & 0x7F].pipes if p[2] and p[0] >= page * 16][0]
    width = area_width(prg, COIN_ROOMS, room_page)
    room = decode_area(prg, COIN_ROOMS, room_page * 16 + width)
    back_ptr, back_page = warp_for(prg, COIN_ROOMS, 0, room_page, 2)
    back = pipe_on_page(areas[back_ptr & 0x7F], back_page)
    x, feet = start_feet(room.header)
    write_map(name, room.grid, room_page * 16, width,
              ["World %s's underground coin room, read from Super Mario Bros.' own level data," % level,
               "and where the pipes in and out of it are."],
              [("%s's pipe that leads here: its left block column, and the block row of its top" % level,
                level_prefix + "_PIPE_COLUMN", entry[0]),
               (None, level_prefix + "_PIPE_ROW", entry[1] + MAP_ROW_OFFSET),
               ("Where Mario drops into the room (level pixels: his left, and his feet)", room_prefix + "_START_X", x),
               (None, room_prefix + "_START_FEET", feet),
               ("The way out: the sideways pipe's mouth (block column, block row of its top half)",
                room_prefix + "_EXIT_COLUMN", room.exit_pipe[0] - room_page * 16),
               (None, room_prefix + "_EXIT_ROW", room.exit_pipe[1] + MAP_ROW_OFFSET),
               ("...which leads back to %s's pipe here (left block column, block row of its top)" % level,
                level_prefix + "_RETURN_PIPE_COLUMN", back[0]),
               (None, level_prefix + "_RETURN_PIPE_ROW", back[1] + MAP_ROW_OFFSET)])


def write_levels(prg):
    """World 1-1's coin room; World 1-2 (its intro, the level, its coin room); every level's enemies"""
    # 1-1's map is hand-made (assets/maps/Level1_1.c); SMB's data says where its pipes go
    area_1_1 = decode_area(prg, AREA_1_1, 16 * 14, strict=False)
    areas = {AREA_1_1 & 0x7F: area_1_1}
    write_coin_room(prg, "Level1_1Bonus", "1-1", AREA_1_1, areas)

    # 1-2: the intro (Mario walks from the castle into a pipe), then the level underground
    intro = decode_area(prg, AREA_1_2_INTRO, PIPE_INTRO_WIDTH)
    x, feet = start_feet(intro.header)
    write_map("Level1_2Intro", intro.grid, 0, PIPE_INTRO_WIDTH,
              ["World 1-2's intro, read from Super Mario Bros.' own level data: Mario walks",
               "from the castle into the pipe (the level itself is underground, Level1_2)."],
              [("Where Mario starts (level pixels: his left, and his feet)", "LEVEL1_2_INTRO_START_X", x),
               (None, "LEVEL1_2_INTRO_START_FEET", feet),
               ("The pipe he walks into: its mouth (block column, block row of its top half)",
                "LEVEL1_2_INTRO_PIPE_COLUMN", intro.intro_pipe[0]),
               (None, "LEVEL1_2_INTRO_PIPE_ROW", intro.intro_pipe[1] + MAP_ROW_OFFSET)])
    width = area_width(prg, AREA_1_2, to_scroll_lock=False)   # (the warp zone is past one)
    level = decode_area(prg, AREA_1_2, width)
    areas[AREA_1_2 & 0x7F] = level
    enemies_1_2 = read_enemy_list(prg, area_address(prg, AREA_1_2, ENEMY_ADDR_H_OFFSETS, ENEMY_DATA_LOW, ENEMY_DATA_HIGH))
    warp_zone = [x for x, y, kind in enemies_1_2 if kind == "WARP_ZONE"][0] // 16
    warp_pipes = [p for p in level.pipes if p[2] and p[0] >= warp_zone]
    exit_area, exit_page = warp_for(prg, AREA_1_2, 0, 10)
    exit_to = pipe_on_page(area_1_1, exit_page)
    x, feet = start_feet(level.header)
    write_map("Level1_2", level.grid, 0, width,
              ["World 1-2, read from Super Mario Bros.' own level data."],
              [("Where Mario drops in (level pixels: his left, and his feet)", "LEVEL1_2_START_X", x),
               (None, "LEVEL1_2_START_FEET", feet),
               ("The way out: the sideways pipe's mouth (block column, block row of its top half),",
                "LEVEL1_2_EXIT_COLUMN", level.exit_pipe[0]),
               (None, "LEVEL1_2_EXIT_ROW", level.exit_pipe[1] + MAP_ROW_OFFSET),
               ("which comes out of 1-1's pipe here (SMB reuses 1-1's end for 1-2's)",
                "LEVEL1_2_EXIT_PIPE_COLUMN", exit_to[0]),
               (None, "LEVEL1_2_EXIT_PIPE_ROW", exit_to[1] + MAP_ROW_OFFSET),
               ("The warp zone: its text starts at this block column, and its pipes (to worlds 4, 3, 2)",
                "LEVEL1_2_WARP_ZONE_COLUMN", warp_zone)] +
              [(None, "LEVEL1_2_WARP_PIPE%d_COLUMN" % (n + 1), p[0]) for n, p in enumerate(warp_pipes)] +
              [(None, "LEVEL1_2_WARP_PIPE_ROW", warp_pipes[0][1] + MAP_ROW_OFFSET)])
    write_coin_room(prg, "Level1_2Bonus", "1-2", AREA_1_2, areas)

    # Every pipe outside 1-1 has a Piranha Plant (SMB adds one to each pipe it draws),
    # except the warp zone's
    for column, top, _ in level.pipes:
        if column < warp_zone:
            enemies_1_2.append((column * 16 + 8, (top + MAP_ROW_OFFSET) * 16, "PIRANHA"))
    write_level_info(prg, [(1, 1), (1, 2)])
    write_enemy_lists([
        ("Level1_1Enemies", "World 1-1", read_enemy_list(prg, ENEMY_LIST_1_1)),
        ("Level1_2Enemies", "World 1-2", [e for e in enemies_1_2 if e[2] != "WARP_ZONE"]),
    ])


HALFWAY_PAGES = 0x91BD   # HalfwayPageNybbles: per world 2 bytes, a nybble per level (1-1's first, high)


def write_level_info(prg, levels):
    """LevelInfo.h: each level's halfway point (the page a restart after dying
    starts from, once Mario's got that far)"""
    h = ["/*", " LEVELINFO.H", "",
         " Things about each level from Super Mario Bros.' own tables. The halfway point",
         " (HalfwayPageNybbles) is a page (16 blocks): once the screen has scrolled that",
         " far, dying restarts the level from there instead of the beginning.", "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/",
         "#ifndef __LevelInfo_h_INCLUDE", "#define __LevelInfo_h_INCLUDE", ""]
    for world, level in levels:
        byte = prg[HALFWAY_PAGES - 0x8000 + (world - 1) * 2 + (level - 1) // 2]
        page = byte >> 4 if level % 2 else byte & 0x0F
        h.append("#define LEVEL%d_%d_HALFWAY_PAGE %d" % (world, level, page))
    h += ["", "#endif", ""]
    open(os.path.join(ROOT, "assets", "maps", "LevelInfo.h"), "w", newline="\n").write("\n".join(h))
    print("wrote assets/maps/LevelInfo.h")


def write_enemy_lists(lists):
    """LevelEnemies (bank 1, with the maps): where each level's enemies start"""
    h = ["/*", " LEVELENEMIES.H", "",
         " Where each level's enemies start, read from Super Mario Bros.' own enemy lists.",
         " 4 bytes each, sorted by x: x (low, high) and y in level pixels (the top-left of",
         " the body, standing on the ground or a platform; a Piranha Plant's is inside its",
         " pipe, a lift's its top), then the ENEMY_* type.", "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/",
         "#ifndef __LevelEnemies_h_INCLUDE", "#define __LevelEnemies_h_INCLUDE", "",
         "#include <gbdk/platform.h>", ""]
    for n, kind in enumerate(ENEMY_TYPES):
        h.append("#define ENEMY_%-10s %d" % (kind, n))
    h.append("")
    c = ["/*", " LEVELENEMIES.C", "", " See LevelEnemies.h.", "",
         " Generated by tools/nes2gb.py from the Super Mario Bros. (NES) ROM.",
         " Do not edit; change the script and rerun it.", "*/", "",
         "#pragma bank 1", "", "#include <gbdk/platform.h>", "", "BANKREF(LevelEnemies)", ""]
    for name, level, enemies in lists:
        enemies = sorted(enemies)   # by x: the game's spawn window relies on it
        h += ["#define %sCount %d" % (name, len(enemies)), "extern const unsigned char %s[];" % name]
        c += ["// %s" % level, "const unsigned char %s[] =" % name, "{"]
        for x, y, kind in enemies:
            c.append("  0x%02X,0x%02X, %3d, %d, // %s at block %g" % (x & 255, x >> 8, y, ENEMY_TYPES.index(kind),
                                                                   kind.lower(), x / 16))
        c += ["};", ""]
    h += ["", "// In switchable ROM bank 1 (maps): switch to BANK(LevelEnemies) before reading them",
          "BANKREF_EXTERN(LevelEnemies)", "", "#endif", ""]
    out = os.path.join(ROOT, "assets", "maps", "LevelEnemies")
    open(out + ".h", "w", newline="\n").write("\n".join(h))
    open(out + ".c", "w", newline="\n").write("\n".join(c))
    for old in ("Level1_1Enemies.c", "Level1_1Enemies.h"):   # (now part of LevelEnemies)
        if os.path.exists(os.path.join(ROOT, "assets", "maps", old)):
            os.remove(os.path.join(ROOT, "assets", "maps", old))
    print("wrote assets/maps/LevelEnemies.c/.h (%s)" % ", ".join("%s: %d" % (n, len(e)) for n, _, e in lists))


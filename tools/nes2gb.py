def read_enemy_list(prg, address):
    """[(x pixels, y pixels of the 16x16 body's top, type name)] for normal mode"""
    i = address - 0x8000
    page = 0
    enemies = []
    while prg[i] != 0xFF:
        column, row = prg[i] >> 4, prg[i] & 0x0F
        if row == 0x0E:           # pipe warp
            if prg[i + 1] & 0x80:
                page += 1
            i += 3
            continue
        flags = prg[i + 1]
        i += 2
        if row == 0x0F:           # set page
            page = flags & 0x3F
            continue
        if flags & 0x80:
            page += 1
        if flags & 0x40:          # hard mode (second quest) only
            continue
        x = (page * 16 + column) * 16
        enemy = flags & 0x3F
        if enemy in ENEMY_GROUPS:
            kind, count, group_row = ENEMY_GROUPS[enemy]
            for k in range(count):
                enemies.append((x + k * 24, (group_row + 1) * 16, kind))
        elif enemy in ENEMY_IDS:
            enemies.append((x, (row + 1) * 16, ENEMY_IDS[enemy]))
        else:
            sys.exit("enemy id %02X at x=%d isn't handled yet" % (enemy, x))
    return enemies



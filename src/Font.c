static const char fontChars[] = " 0123456789ADEGILMORTUPVWx-";

void fontLoad(void) {
    set_bkg_data(FONT_FIRST_TILE, sizeof(fontTiles) / 16, fontTiles);
}

uint8_t fontTile(char c) {
    uint8_t i;
    for (i = 0; fontChars[i]; i++) {
        if (fontChars[i] == c) return FONT_FIRST_TILE + i;
    }
    return FONT_BLANK_TILE;
}

void fontPrint(uint8_t x, uint8_t y, const char *text) {
    uint8_t tile;
    while (*text) {
        tile = fontTile(*text++);
        set_bkg_tile_xy(x++, y, tile);
    }
}
